# Map a 0-based event index to (event_name, status, consent, forwarded_count, error, consent_signals)
def _event_profile(idx: int):
    """Return deterministic (event_name, status, consent, forwarded_count, error, consent_signals)
    for a given 0-based event index.

    Distribution (100 events target):
      - event_name: descending funnel — PageView 40, ViewContent 26,
                    AddToCart 18, InitiateCheckout 10, Purchase 6.
      - status:
          forwarded        — ~60 events (idx % 10 in {0,1,2,3,5,6})
          skipped_no_consent — ~20 events (idx % 10 in {4,8}, consent=False)
          failed           — ~10 events (idx % 10 == 7)
          duplicate        — ~7 events  (idx % 15 == 14)
          received         — ~3 events  (idx % 30 == 29)

    consent_signals (Consent Mode v2 granular dict):
      - consent=True events: ad_storage, analytics_storage, ad_user_data all
        granted; ad_personalization granted for ~70% (idx % 10 < 7), denied
        for the rest — producing realistic per-signal rate differences.
      - consent=False (skipped_no_consent) events: all 4 keys denied.
    """
    # event_name: 50-cycle mapping producing a descending funnel over 100 events.
    # Target distribution: PageView 40, ViewContent 26, AddToCart 18,
    #                      InitiateCheckout 10, Purchase 6  (sum = 100).
    # Two complete cycles of 50 cover all 100 events deterministically.
    #   idx % 50 in  0-19  → PageView        (20/cycle × 2 = 40)
    #   idx % 50 in 20-32  → ViewContent     (13/cycle × 2 = 26)
    #   idx % 50 in 33-41  → AddToCart       ( 9/cycle × 2 = 18)
    #   idx % 50 in 42-46  → InitiateCheckout( 5/cycle × 2 = 10)
    #   idx % 50 in 47-49  → Purchase        ( 3/cycle × 2 =  6)
    slot = idx % 50
    if slot <= 19:
        event_name = "PageView"
    elif slot <= 32:
        event_name = "ViewContent"
    elif slot <= 41:
        event_name = "AddToCart"
    elif slot <= 46:
        event_name = "InitiateCheckout"
    else:
        event_name = "Purchase"

    # status
    if idx % 15 == 14:
        status = "duplicate"
        consent = True
        forwarded_count = 0
        error = None
    elif idx % 30 == 29:
        status = "received"
        consent = True
        forwarded_count = 0
        error = None
    elif idx % 10 == 7:
        status = "failed"
        consent = True
        forwarded_count = 0
        # Deterministic error messages
        _errors = [
            "[meta_capi] HTTP 400: Invalid pixel_id",
            "[ga4_mp] HTTP 500: Internal Server Error",
            "[meta_capi] HTTP 403: Access token expired",
            "[ga4_mp] HTTP 429: Rate limit exceeded",
        ]
        error = _errors[idx % len(_errors)]
    elif idx % 10 in {4, 8}:
        status = "skipped_no_consent"
        consent = False
        forwarded_count = 0
        error = None
    else:
        status = "forwarded"
        consent = True
        # forwarded_count: 1 or 2 depending on which destinations matched consent
        forwarded_count = 2 if idx % 3 != 0 else 1
        error = None

    # Consent Mode v2 granular signals — populated deterministically so the
    # dashboard granular breakdown renders richly with realistic per-signal rates.
    if consent:
        # ad_personalization granted for ~70% of consented events (idx % 10 < 7)
        ad_personalization = (idx % 10) < 7
        consent_signals = {
            "ad_storage": True,
            "analytics_storage": True,
            "ad_user_data": True,
            "ad_personalization": ad_personalization,
        }
    else:
        # All signals denied for no-consent events
        consent_signals = {
            "ad_storage": False,
            "analytics_storage": False,
            "ad_user_data": False,
            "ad_personalization": False,
        }

    return event_name, status, consent, forwarded_count, error, consent_signals


def _identity_profile(event_name: str, idx: int) -> dict:
    """Return a deterministic RAW (pre-hash) user_data dict for a demo event.

    Identity completeness is correlated with intent: high-value events
    (Purchase / InitiateCheckout) carry richer signals than PageViews.  This
    produces a realistic spread of Match-Quality tiers and per-field coverage
    in the dashboard.  No real PII — emails use the reserved .invalid TLD.
    """
    user_num = idx % 20
    em = f"demouser{user_num:02d}@example.invalid"
    ph = f"+9053300{user_num:05d}"
    fbc = f"fb.1.{1700000000 + idx}.IwAR{idx:06d}"
    fbp = f"fb.1.{1700000000 + idx}.{(idx * 7) % 999999}"
    ext = f"ayazdemo-cust-{user_num:04d}"
    ip = f"85.10.{idx % 255}.{(idx * 7) % 255}"
    ua = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"

    if event_name in ("Purchase", "InitiateCheckout"):
        bucket = idx % 4
        if bucket == 0:
            return {"email": em, "phone": ph, "fbc": fbc, "fbp": fbp,
                    "external_id": ext, "client_ip_address": ip,
                    "client_user_agent": ua}
        if bucket == 1:
            return {"email": em, "phone": ph, "fbp": fbp, "external_id": ext}
        if bucket == 2:
            return {"email": em, "phone": ph, "fbc": fbc,
                    "client_ip_address": ip, "client_user_agent": ua}
        return {"email": em, "phone": ph, "fbp": fbp}

    if event_name in ("AddToCart", "ViewContent"):
        bucket = idx % 3
        if bucket == 0:
            return {"email": em, "fbp": fbp, "client_ip_address": ip,
                    "client_user_agent": ua}
        if bucket == 1:
            return {"email": em, "fbp": fbp}
        return {"fbp": fbp, "client_ip_address": ip, "client_user_agent": ua}

    # PageView — poorest identity coverage
    if idx % 2 == 0:
        return {"client_ip_address": ip, "client_user_agent": ua}
    return {"fbp": fbp, "client_ip_address": ip, "client_user_agent": ua}


def _seed_tracking(db, tenant: Tenant) -> dict:
    """Seed M7 tracking demo data: one TrackingSource, two EventDestinations,
    and 100 ConversionEvents spread across the last 14 days.

    Idempotency
    -----------
    - TrackingSource:  matched by ``public_token`` (the truly stable identity —
      it is embedded in the snippet embed URL printed at the end of the seed
      run) rather than by ``name``.  Matching by name would silently break
      idempotency — and collide on the unique ``public_token`` constraint —
      any time the demo brand copy changes, since a rename would no longer
      find the previously-seeded row.  ``name``/``domain`` are self-healed
      (updated in place) on every run so a brand-copy change still propagates
      to existing demo databases instead of leaving stale data behind.
    - EventDestinations:  skip if the source already has destinations (avoids
      re-adding on second run after the source was created).
    - ConversionEvents:  skip entire block if the source already has any events
      (count-based guard).  Deterministic event_id values prevent accidental
      duplication even if the guard is bypassed.

    Returns dict with counts.
    """
    from sqlalchemy import func as _func

    counts = {"tracking_sources": 0, "destinations": 0, "events_inserted": 0}

    # ── TrackingSource ─────────────────────────────────────────────────────
    source = db.scalar(
        select(TrackingSource).where(
            TrackingSource.tenant_id == tenant.id,
            TrackingSource.public_token == _TRACKING_PUBLIC_TOKEN,
        )
    )
    if source is None:
        source = TrackingSource(
            tenant_id=tenant.id,
            name=_TRACKING_SOURCE_NAME,
            domain="demo.ayaz.app",
            public_token=_TRACKING_PUBLIC_TOKEN,
            is_active=True,
            # KVKK açık rıza: snippet reads the CMP's consent cookie/dataLayer key,
            # so seeded consent=true events are coherent with a wired consent signal.
            consent_cookie_var="ayaz_consent",
        )
        db.add(source)
        db.flush()
        print(f"  Created TrackingSource: {_TRACKING_SOURCE_NAME} ({source.id})")
        counts["tracking_sources"] = 1
    else:
        if source.name != _TRACKING_SOURCE_NAME or source.domain != "demo.ayaz.app":
            source.name = _TRACKING_SOURCE_NAME
            source.domain = "demo.ayaz.app"
            db.flush()
        print(f"  TrackingSource already exists: {_TRACKING_SOURCE_NAME} ({source.id})")

    # ── EventDestinations ─────────────────────────────────────────────────
    existing_dest_count = db.scalar(
        select(_func.count()).select_from(EventDestination).where(
            EventDestination.tracking_source_id == source.id
        )
    ) or 0

    if existing_dest_count == 0:
        # meta_capi — consent_required=True (KVKK/GDPR strict)
        meta_dest = EventDestination(
            tenant_id=tenant.id,
            tracking_source_id=source.id,
            platform="meta_capi",
            config={
                "pixel_id": "1234567890123456",
                "action_source": "website",
            },
            vault_secret_ref="demo/tracking/meta_capi_access_token",
            consent_required=True,
            is_active=True,
        )
        # ga4_mp — consent_required=False (GA4 collects without strict consent)
        ga4_dest = EventDestination(
            tenant_id=tenant.id,
            tracking_source_id=source.id,
            platform="ga4_mp",
            config={
                "measurement_id": "G-DEMO000001",
            },
            vault_secret_ref="demo/tracking/ga4_api_secret",
            consent_required=False,
            is_active=True,
        )
        db.add_all([meta_dest, ga4_dest])
        db.flush()
        print(f"  Created EventDestination: meta_capi (consent_required=True)")
        print(f"  Created EventDestination: ga4_mp (consent_required=False)")
        counts["destinations"] = 2
    else:
        print(f"  EventDestinations already exist ({existing_dest_count} found) — skipping")

    # ── ConversionEvents ──────────────────────────────────────────────────
    existing_event_count = db.scalar(
        select(_func.count()).select_from(ConversionEvent).where(
            ConversionEvent.tracking_source_id == source.id
        )
    ) or 0

    if existing_event_count > 0:
        print(
            f"  ConversionEvents already exist ({existing_event_count} rows) — skipping"
        )
        db.commit()
        return counts

    # Generate 100 events spread across the last 14 days.
    # Day offset is index-based: idx // 7 gives 0–14 (14 days, ~7 events/day).
    _NUM_EVENTS = 100
    _TRACKING_END_DATE = _RICH_END_DATE  # reuse the same end-date anchor

    now_utc = datetime.now(timezone.utc)

    for idx in range(_NUM_EVENTS):
        # Spread events across 14 days: idx // 7 days back from end date
        day_offset = idx // 7  # 0 to 14
        event_date = _TRACKING_END_DATE - timedelta(days=day_offset)
        # Hour within the day: deterministic (idx % 24)
        event_hour = idx % 24
        event_dt = datetime(
            event_date.year, event_date.month, event_date.day,
            event_hour, (idx * 7) % 60, (idx * 13) % 60,
            tzinfo=timezone.utc,
        )
        event_time_iso = event_dt.isoformat()
        # Stable created_at slightly after event_time (seconds after = idx % 30)
        created_at_dt = event_dt.replace(second=min(59, (event_dt.second + idx % 30) % 60))
        created_at_iso = created_at_dt.isoformat()

        # Deterministic event_id — seed uses source token + index
        event_id = f"demo-evt-{_TRACKING_PUBLIC_TOKEN[:10]}-{idx:04d}"

