# ── Rich fact data generation ─────────────────────────────────────────────────


def _seed_rich_facts(db, tenant: Tenant, accounts: dict[str, ConnectedAccount]) -> tuple[int, int]:
    """Generate 45 days of FactDailyMetrics across 3 channels with anomalies.

    Returns (inserted, updated) counts.
    """
    inserted = 0
    updated = 0
    now_utc = datetime.now(timezone.utc)

    date_range = [
        _RICH_START_DATE + timedelta(days=d)
        for d in range(45)
    ]

    for ch_idx, ch_spec in enumerate(_CHANNEL_SPECS):
        channel_key = ch_spec["channel_key"]
        channel = _get_or_create_channel(db, channel_key)
        account = accounts[channel_key]

        for camp_idx, camp in enumerate(ch_spec["campaigns"]):
            campaign = _get_or_create_campaign(
                db, tenant.id, channel,
                external_id=camp["camp_ext"],
                name=camp["camp_name"],
            )
            adset = _get_or_create_adset(
                db, tenant.id, campaign,
                external_id=camp["adset_ext"],
                name=camp["adset_name"],
            )
            ad = _get_or_create_ad(
                db, tenant.id, adset,
                external_id=camp["ad_ext"],
                name=camp["ad_name"],
            )

            for day_idx, d in enumerate(date_range):
                _ensure_dim_date(db, d)

                # Base values with deterministic noise
                impressions = int(_noise(Decimal(camp["impressions"]), day_idx, camp_idx))
                clicks = max(1, int(_noise(Decimal(camp["clicks"]), day_idx, camp_idx + 1)))
                cost = _noise(camp["cost"], day_idx, camp_idx + 2).quantize(Decimal("0.01"))
                conversions = _noise(camp["conversions"], day_idx, camp_idx + 3).quantize(Decimal("0.01"))
                conv_value = _noise(camp["conv_value"], day_idx, camp_idx + 4).quantize(Decimal("0.01"))

                # Clamp to reasonable minimums
                clicks = min(clicks, impressions)
                cost = max(Decimal("0.01"), cost)
                conversions = max(Decimal("0"), conversions)
                conv_value = max(Decimal("0"), conv_value)

                # ── Anomaly injection (last 7 days = day_idx >= _ANOMALY_START_OFFSET) ──
                in_anomaly_window = day_idx >= _ANOMALY_START_OFFSET

                if in_anomaly_window and camp.get("anomaly") == "roas_drop":
                    # ROAS drop on google_ads Brand Search: halve conversion value
                    conv_value = (conv_value * Decimal("0.35")).quantize(Decimal("0.01"))

                elif in_anomaly_window and camp.get("anomaly") == "spend_spike":
                    # Spend spike on meta_ads Retargeting: triple cost
                    cost = (cost * Decimal("3.2")).quantize(Decimal("0.01"))

                elif in_anomaly_window and camp.get("anomaly") == "zero_conversions":
                    # Zero conversions on tiktok_ads Viral Creative: conversions → 0
                    conversions = Decimal("0")
                    conv_value = Decimal("0")

                # Check if fact row already exists for this grain
                existing = db.scalar(
                    select(FactDailyMetrics).where(
                        FactDailyMetrics.tenant_id == tenant.id,
                        FactDailyMetrics.connected_account_id == account.id,
                        FactDailyMetrics.channel_id == channel.id,
                        FactDailyMetrics.campaign_id == campaign.id,
                        FactDailyMetrics.adset_id == adset.id,
                        FactDailyMetrics.ad_id == ad.id,
                        FactDailyMetrics.date_key == d,
                    )
                )

                if existing is None:
                    fact = FactDailyMetrics(
                        tenant_id=tenant.id,
                        connected_account_id=account.id,
                        channel_id=channel.id,
                        campaign_id=campaign.id,
                        adset_id=adset.id,
                        ad_id=ad.id,
                        date_key=d,
                        impressions=impressions,
                        clicks=clicks,
                        cost_raw=cost,
                        cost_ccy=ch_spec["cost_ccy"],
                        conversions=conversions,
                        conversion_value_raw=conv_value,
                        conversion_value_ccy=ch_spec["cost_ccy"],
                        # Placeholder: no FX conversion — base_ccy = raw
                        cost_base_ccy=cost,
                        conv_value_base_ccy=conv_value,
                        ingested_at=now_utc,
                    )
                    db.add(fact)
                    inserted += 1
                else:
                    existing.impressions = impressions
                    existing.clicks = clicks
                    existing.cost_raw = cost
                    existing.cost_ccy = ch_spec["cost_ccy"]
                    existing.conversions = conversions
                    existing.conversion_value_raw = conv_value
                    existing.conversion_value_ccy = ch_spec["cost_ccy"]
                    existing.cost_base_ccy = cost
                    existing.conv_value_base_ccy = conv_value
                    existing.ingested_at = now_utc
                    updated += 1

        # Flush per channel to keep memory bounded
        db.flush()

    db.commit()
    return inserted, updated


