def _seed_budget(db, tenant: Tenant) -> dict:
    """Seed M12 Budget Planner demo data: one saved BudgetPlan for next month,
    with allocations computed from the seeded warehouse history.

    Idempotency: skip if the tenant already has any BudgetPlan.
    """
    from sqlalchemy import func as _func
    from ayaz.services.budget_planner import allocate_budget

    counts = {"budget_plans": 0}

    existing = db.scalar(
        select(_func.count()).select_from(BudgetPlan).where(
            BudgetPlan.tenant_id == tenant.id
        )
    ) or 0
    if existing > 0:
        print(f"  BudgetPlans already exist ({existing} rows) — skipping")
        return counts

    # Next month relative to the rich demo window.
    end = _RICH_END_DATE
    if end.month == 12:
        period_month = f"{end.year + 1}-01"
    else:
        period_month = f"{end.year}-{end.month + 1:02d}"

    total_budget = 150000.0
    try:
        allocations = allocate_budget(
            db,
            tenant.id,
            total_budget=total_budget,
            objective="balanced",
            lookback_days=90,
            currency="TRY",
            as_of=end,
        )
    except Exception as exc:  # pragma: no cover - defensive
        print(f"  Budget allocation failed ({exc}) — storing plan without snapshot")
        allocations = None

    plan = BudgetPlan(
        tenant_id=tenant.id,
        name=f"{period_month} Bütçe Planı",
        period_month=period_month,
        total_budget=total_budget,
        currency="TRY",
        objective="balanced",
        lookback_days=90,
        allocations=allocations,
        status="active",
    )
    db.add(plan)
    db.flush()
    counts["budget_plans"] = 1

    # Also seed the CURRENT month plan so Plan-vs-Gerçekleşen has real actuals.
    # Budget sized near the month's real spend so pacing reads realistically.
    current_month = f"{end.year}-{end.month:02d}"
    current_budget = 450000.0
    try:
        cur_alloc = allocate_budget(
            db, tenant.id, total_budget=current_budget, objective="balanced",
            lookback_days=90, currency="TRY", as_of=end,
        )
    except Exception:  # pragma: no cover
        cur_alloc = None
    cur_plan = BudgetPlan(
        tenant_id=tenant.id,
        name=f"{current_month} Bütçe Planı",
        period_month=current_month,
        total_budget=current_budget,
        currency="TRY",
        objective="balanced",
        lookback_days=90,
        allocations=cur_alloc,
        status="active",
    )
    db.add(cur_plan)
    db.flush()
    counts["budget_plans"] = 2

    db.commit()
    print(f"  Created 2 BudgetPlans: {plan.name}, {cur_plan.name}")
    return counts


