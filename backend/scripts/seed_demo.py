"""Demo seed script — populates the full AYAZ app with realistic demo data.

Usage
-----
From the ``backend/`` directory:

    python -m scripts.seed_demo          # as a module
    python scripts/seed_demo.py          # as a script

The script is fully idempotent: running it multiple times will not duplicate
data.  It creates:

1. A demo Tenant (name "AYAZ Demo", base_currency "TRY").
2. A demo User (email ``demo@ayaz.app``, password ``demo12345``).
3. An owner Membership linking the user to the tenant.
4. Three ConnectedAccounts: google_ads, meta_ads, tiktok_ads.
5. 45 days of FactDailyMetrics for 3 channels x 2-3 campaigns each, with
   realistic baselines, mild noise, and injected anomalies in the last 7 days:
     - google_ads / "Brand Search"   : ROAS drop in days -6 to -1  (critical)
     - meta_ads  / "Retargeting"     : spend spike in days -5 to -1 (warning)
     - tiktok_ads / "Viral Creative" : zero conversions in days -7 to -1
6. A FeedSource ("Demo Ürün Feed'i") with products from sample_feed.xml, plus
   two FeedChannels (google_shopping XML + meta_catalog CSV) each with rules.
7. Insights generated by calling services.insights.generate_insights.
8. One ReportDefinition (white-label) with a SharedReport link (if the reports
   model is importable — guarded with try/except for forward-compat).

Connector fixtures
------------------
``sample``    — ``tests/fixtures/sample_metrics.json`` (3 rows, 2024-03)
``google_ads`` — ``tests/fixtures/google_ads_search_stream.json`` (3 rows, 2024-06)

The GoogleAdsConnector is used in *fixture mode*: we directly call
``normalize()`` on the pre-recorded fixture rather than calling ``fetch()``
(which would hit the real API).  We do this by subclassing GoogleAdsConnector
and overriding ``fetch()`` to load the local fixture instead.

Anomaly injection
-----------------
All fact values are generated deterministically via index-based arithmetic
(no random seed needed — same index always produces the same value).
Anomalies are injected by overriding the computed value for specific
(channel, campaign, day-offset) combinations in the last 7 days:
  - ROAS drop: conversion_value_raw halved on google_ads "Brand Search"
  - Spend spike: cost_raw tripled on meta_ads "Retargeting"
  - Zero conversions: conversions forced to 0 on tiktok_ads "Viral Creative"

Exit codes
----------
0 — success
1 — DB unreachable (prints the error and instructions)
"""

